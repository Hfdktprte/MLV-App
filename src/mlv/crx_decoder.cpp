static void set_be32(uint8_t *p, uint32_t value)
{
    p[0] = value >> 24;
    p[1] = value >> 16;
    p[2] = value >> 8;
    p[3] = value;
}

static void set_be16(uint8_t *p, uint16_t value)
{
    p[0] = value >> 8;
    p[1] = value;
}

int crx_decode_frame(const uint8_t *input, size_t input_size,
                     uint16_t *output, uint32_t width, uint32_t height)
{
    if (!input || !output || input_size <= 0x34 ||
        memcmp(input, "\xff\x00\x00\x30", 4) ||
        ((uint32_t)input[10] << 8 | input[11]) != width ||
        ((uint32_t)input[14] << 8 | input[15]) != height)
        return -1;

    const size_t payload_size = input_size - 0x34;
    const size_t wrapper_size = sizeof(cr3_header) + 8 + payload_size;
    uint8_t *wrapper = (uint8_t *)malloc(wrapper_size);
    if (!wrapper)
        return -1;

    memcpy(wrapper, cr3_header, sizeof(cr3_header));
    for (size_t i = 0; i + 32 <= sizeof(cr3_header); ++i)
    {
        if (!memcmp(wrapper + i, "CRAW", 4))
        {
            set_be16(wrapper + i + 28, (uint16_t)width);
            set_be16(wrapper + i + 30, (uint16_t)height);
            break;
        }
    }
    memcpy(wrapper + 0x1f3, input, 0x34);
    set_be32(wrapper + 0x2cc, (uint32_t)payload_size);
    set_be32(wrapper + sizeof(cr3_header), (uint32_t)(payload_size + 8));
    memcpy(wrapper + sizeof(cr3_header) + 4, "mdat", 4);
    memcpy(wrapper + sizeof(cr3_header) + 8, input + 0x34, payload_size);

    libraw_data_t *raw = libraw_init(0);
    int result = raw ? libraw_open_buffer(raw, wrapper, wrapper_size) : LIBRAW_UNSUFFICIENT_MEMORY;
    if (result == LIBRAW_SUCCESS)
        result = libraw_unpack(raw);
    if (result == LIBRAW_SUCCESS && raw->rawdata.raw_image &&
        raw->sizes.raw_width == width && raw->sizes.raw_height == height)
        memcpy(output, raw->rawdata.raw_image, (size_t)width * height * sizeof(*output));
    else if (result == LIBRAW_SUCCESS)
        result = LIBRAW_DATA_ERROR;

    if (raw)
        libraw_close(raw);
    free(wrapper);
    return result;
}
